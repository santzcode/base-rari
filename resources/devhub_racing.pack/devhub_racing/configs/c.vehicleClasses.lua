-- Function to get vehicle class based on model hash
function GetVehicleClassByHash(vehicleHash)
    for class, vehicles in pairs(Config.VehicleClasses) do
        for _, hash in ipairs(vehicles) do
            if hash == vehicleHash then
                return class
            end
        end
    end
    return "D" -- Default to lowest class if not found
end

-- Function to check if vehicle is allowed in race
function IsVehicleAllowedInRace(vehicleHash, raceVehicleClass)
    if raceVehicleClass == "ALL" then
        return true
    end
    
    local vehicleClass = GetVehicleClassByHash(vehicleHash)
    return vehicleClass == raceVehicleClass
end